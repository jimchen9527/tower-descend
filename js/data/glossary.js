// glossify(html)：把文本里第一次出现的每个术语包成可点按的 term 标记。
// 只包第一次出现 —— 一段卡面文本里同一术语点一处就够了，避免满屏下划线。
// 注意每次渲染都从原始文本重建，不会重复包裹。
function glossify(html) {
  if (!html) return html || '';
  let out = String(html);
  const terms = Object.keys(GLOSSARY).sort(function (a, b) { return b.length - a.length; });
  for (let i = 0; i < terms.length; i++) {
    const t = terms[i];
    const at = out.indexOf(t);
    if (at === -1) continue;
    out = out.slice(0, at) +
      '<span class="term" data-term="' + t + '">' + t + '</span>' +
      out.slice(at + t.length);
  }
  return out;
}
